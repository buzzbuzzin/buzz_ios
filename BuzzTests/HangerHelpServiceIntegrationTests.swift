    // MARK: - Toggle Follow Comment

    func testToggleFollowComment_addsAndRemoves() async throws {
        let postId = try await createTestPost(title: "Follow Comment Post")
        let commentId = try await createTestComment(postId: postId, body: "Followable comment")

        // Follow the comment
        try await service.toggleFollowComment(commentId: commentId, userId: TestUser.id)

        // We can verify by checking Supabase directly
        let follows: [HangerFollowedComment] = try await supabase
            .from("hanger_followed_comments")
            .select()
            .eq("user_id", value: TestUser.id.uuidString)
            .eq("comment_id", value: commentId.uuidString)
            .execute()
            .value
        XCTAssertEqual(follows.count, 1, "Comment should have a follow record")

        // Unfollow
        try await service.toggleFollowComment(commentId: commentId, userId: TestUser.id)

        let followsAfter: [HangerFollowedComment] = try await supabase
            .from("hanger_followed_comments")
            .select()
            .eq("user_id", value: TestUser.id.uuidString)
            .eq("comment_id", value: commentId.uuidString)
            .execute()
            .value
        XCTAssertTrue(followsAfter.isEmpty, "Follow record should be removed")
    }

