    func testNestedComment_appearsAsReply() async throws {
        let postId = try await createTestPost(title: "Nested Comment Post")
        let parentId = try await createTestComment(postId: postId, body: "Parent comment", depth: 0)
        let childId = try await createTestComment(
            postId: postId,
            body: "Child reply",
            parentCommentId: parentId,
            depth: 1
        )

        // Re-fetch comments to build the tree
        await service.fetchComments(postId: postId, currentUserId: TestUser.id)

        // Find parent in top-level
        let parent = service.comments.first { $0.id == parentId }
        XCTAssertNotNil(parent, "Parent comment should be in top-level")

        // Child should be in parent's replies
        let child = parent?.replies.first { $0.id == childId }
        XCTAssertNotNil(child, "Child reply should be nested under parent")
        XCTAssertEqual(child?.comment.body, "Child reply")
        XCTAssertEqual(child?.comment.depth, 1)
    }

