    // MARK: - Toggle Save Post

    func testToggleSavePost_addsAndRemoves() async throws {
        let postId = try await createTestPost(title: "Save Toggle Post")

        // Save the post
        try await service.toggleSavePost(postId: postId, userId: TestUser.id)

        // Verify saved state
        await service.fetchAllPosts(currentUserId: TestUser.id)
        var match = service.posts.first { $0.id == postId }
        XCTAssertTrue(match?.isSavedByCurrentUser ?? false, "Post should be saved")

        // Verify it appears in saved posts
        await service.fetchSavedPosts(currentUserId: TestUser.id)
        XCTAssertTrue(service.savedPosts.contains { $0.id == postId }, "Post should appear in saved list")

        // Unsave
        try await service.toggleSavePost(postId: postId, userId: TestUser.id)

        await service.fetchAllPosts(currentUserId: TestUser.id)
        match = service.posts.first { $0.id == postId }
        XCTAssertFalse(match?.isSavedByCurrentUser ?? true, "Post should be unsaved")

        // Verify it no longer appears in saved posts
        await service.fetchSavedPosts(currentUserId: TestUser.id)
        XCTAssertFalse(service.savedPosts.contains { $0.id == postId }, "Post should not appear in saved list")
    }

