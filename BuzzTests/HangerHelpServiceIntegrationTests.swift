    // MARK: - Multiple Interactions on Same Post

    func testMultipleInteractions_coexist() async throws {
        let postId = try await createTestPost(title: "Multi Interaction Post")

        // Like + Save + Follow the same post
        try await service.togglePostLike(postId: postId, userId: TestUser.id)
        try await service.toggleSavePost(postId: postId, userId: TestUser.id)
        try await service.toggleFollowPost(postId: postId, userId: TestUser.id)

        await service.fetchAllPosts(currentUserId: TestUser.id)
        let match = service.posts.first { $0.id == postId }
        XCTAssertTrue(match?.isLikedByCurrentUser ?? false)
        XCTAssertTrue(match?.isSavedByCurrentUser ?? false)
        XCTAssertTrue(match?.isFollowedByCurrentUser ?? false)

        // Clean up all interactions
        try await service.togglePostLike(postId: postId, userId: TestUser.id)
        try await service.toggleSavePost(postId: postId, userId: TestUser.id)
        try await service.toggleFollowPost(postId: postId, userId: TestUser.id)
    }
