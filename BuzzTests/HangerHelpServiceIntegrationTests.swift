import XCTest
import Supabase
@testable import Buzz

@MainActor
final class HangerHelpServiceIntegrationTests: IntegrationTestCase {

    private var service: HangerHelpService!

    /// The first active topic fetched from the DB (used to create test posts).
    private var testTopicId: UUID!

    override func setUp() async throws {
        try await super.setUp()
        service = HangerHelpService()

        // Fetch topics so we have a valid topic ID for creating posts
        await service.fetchTopics()
        guard let firstTopic = service.topics.first else {
            XCTFail("No active topics found in the database – seed hanger_topics first")
            return
        }
        testTopicId = firstTopic.id
    }

    override func tearDown() async throws {
        service = nil
        testTopicId = nil
        try await super.tearDown()
    }

    // MARK: - Helper: Create a post and track for cleanup

    @discardableResult
    private func createTestPost(
        title: String = "Integration Test Post",
        body: String = "Auto-generated by integration test"
    ) async throws -> UUID {
        try await service.createPost(
            topicId: testTopicId,
            authorId: TestUser.id,
            title: title,
            body: body
        )

        // Fetch posts to find the one we just created
        await service.fetchAllPosts(currentUserId: TestUser.id)
        guard let created = service.posts.first(where: { $0.post.title == title }) else {
            XCTFail("Created post '\(title)' not found after fetch")
            return UUID()
        }

        trackForCleanup(table: "hanger_posts", id: created.id)
        return created.id
    }

    @discardableResult
    private func createTestComment(
        postId: UUID,
        body: String = "Integration test comment",
        parentCommentId: UUID? = nil,
        depth: Int = 0
    ) async throws -> UUID {
        try await service.createComment(
            postId: postId,
            parentCommentId: parentCommentId,
            authorId: TestUser.id,
            body: body,
            depth: depth
        )

        // Fetch comments to find the one we just created
        await service.fetchComments(postId: postId, currentUserId: TestUser.id)
        guard let created = findComment(body: body, in: service.comments) else {
            XCTFail("Created comment '\(body)' not found after fetch")
            return UUID()
        }

        trackForCleanup(table: "hanger_comments", id: created.id)
        return created.id
    }

    /// Recursively searches the comment tree for a comment with the given body.
    private func findComment(body: String, in comments: [HangerCommentWithAuthor]) -> HangerCommentWithAuthor? {
        for comment in comments {
            if comment.comment.body == body {
                return comment
            }
            if let found = findComment(body: body, in: comment.replies) {
                return found
            }
        }
        return nil
    }

