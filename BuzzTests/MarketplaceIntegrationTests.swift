    func testTransactionLifecycle_meetup() async throws {
        let listing = try await createTestListing(title: "Meetup Lifecycle Listing", price: 250)
        let fakeBuyerId = UUID()

        let transaction: MarketplaceTransaction
        do {
            transaction = try await service.createMeetupTransaction(
                listingId: listing.id,
                buyerId: fakeBuyerId,
                sellerId: TestUser.id,
                offerId: nil,
                amount: 250
            )
            trackForCleanup(table: "marketplace_transactions", id: transaction.id)
        } catch {
            throw XCTSkip("Transaction INSERT blocked by RLS: \(error.localizedDescription)")
        }

        // Schedule meetup (test user is buyer or seller, both allowed)
        let meetupDate = Date().addingTimeInterval(86400)
        try await service.scheduleMeetup(
            transactionId: transaction.id,
            locationName: "Test Park, CA",
            lat: 37.77,
            lng: -122.42,
            scheduledAt: meetupDate
        )

        // Verify meetup details persisted
        let afterSchedule: MarketplaceTransaction = try await supabase
            .from("marketplace_transactions")
            .select()
            .eq("id", value: transaction.id.uuidString)
            .single()
            .execute()
            .value
        XCTAssertEqual(afterSchedule.meetupLocationName, "Test Park, CA")
        XCTAssertNotNil(afterSchedule.meetupScheduledAt)

        // Seller confirms meetup complete
        try await service.confirmMeetupComplete(
            transactionId: transaction.id,
            byUserId: TestUser.id
        )

        // Verify seller confirmed, but transaction NOT completed (needs buyer too)
        let afterConfirm: MarketplaceTransaction = try await supabase
            .from("marketplace_transactions")
            .select()
            .eq("id", value: transaction.id.uuidString)
            .single()
            .execute()
            .value
        XCTAssertNotNil(afterConfirm.sellerConfirmedAt)
        XCTAssertNil(afterConfirm.buyerConfirmedAt, "Buyer has not confirmed yet")
        XCTAssertNotEqual(afterConfirm.status, .meetupCompleted,
                          "Should not be completed until both parties confirm")
    }

