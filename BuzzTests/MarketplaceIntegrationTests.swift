    func testSubmitAndFetchReview() async throws {
        let listing = try await createTestListing(title: "Review Test Listing", price: 100)
        let fakeBuyerId = UUID()

        let transaction: MarketplaceTransaction
        do {
            transaction = try await createTestShipTransaction(
                listingId: listing.id, amount: 100, buyerId: fakeBuyerId
            )
        } catch {
            throw XCTSkip("Transaction needed for review test, blocked by RLS: \(error.localizedDescription)")
        }

        // Submit review from test user (seller) to fake buyer
        try await service.submitReview(
            transactionId: transaction.id,
            fromUserId: TestUser.id,
            toUserId: fakeBuyerId,
            rating: 5,
            comment: "Great buyer, quick payment!"
        )

        // Fetch reviews for the fake buyer to find ours
        let reviews = try await service.fetchReviewsForUser(userId: fakeBuyerId)
        let match = reviews.first { $0.review.transactionId == transaction.id }

        XCTAssertNotNil(match)
        XCTAssertEqual(match?.review.rating, 5)
        XCTAssertEqual(match?.review.comment, "Great buyer, quick payment!")
        XCTAssertEqual(match?.review.fromUserId, TestUser.id)

        if let reviewId = match?.id {
            trackForCleanup(table: "marketplace_reviews", id: reviewId)
        }
    }

    func testHasUserReviewed() async throws {
        let listing = try await createTestListing(title: "HasReviewed Test Listing", price: 100)
        let fakeBuyerId = UUID()

        let transaction: MarketplaceTransaction
        do {
            transaction = try await createTestShipTransaction(
                listingId: listing.id, amount: 100, buyerId: fakeBuyerId
            )
        } catch {
            throw XCTSkip("Transaction needed for review test, blocked by RLS: \(error.localizedDescription)")
        }

        // Before submitting a review
        let before = await service.hasUserReviewed(
            transactionId: transaction.id,
            userId: TestUser.id
        )
        XCTAssertFalse(before, "Should not have reviewed yet")

        // Submit review
        try await service.submitReview(
            transactionId: transaction.id,
            fromUserId: TestUser.id,
            toUserId: fakeBuyerId,
            rating: 4,
            comment: "Good transaction"
        )

        // After submitting
        let after = await service.hasUserReviewed(
            transactionId: transaction.id,
            userId: TestUser.id
        )
        XCTAssertTrue(after, "Should show as reviewed after submission")

        // Clean up review
        struct ReviewId: Decodable { let id: UUID }
        let createdReviews: [ReviewId] = try await supabase
            .from("marketplace_reviews")
            .select("id")
            .eq("transaction_id", value: transaction.id.uuidString)
            .eq("from_user_id", value: TestUser.id.uuidString)
            .execute()
            .value
        for r in createdReviews {
            trackForCleanup(table: "marketplace_reviews", id: r.id)
        }
    }

