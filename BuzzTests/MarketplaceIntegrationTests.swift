    // MARK: - Helpers

    /// Creates a listing owned by the test user and tracks it for cleanup.
    @discardableResult
    private func createTestListing(
        title: String = "Integration Test Drone",
        description: String = "Auto-generated by integration test",
        price: Decimal = 299.99,
        category: MarketplaceCategory = .drones,
        condition: ListingCondition = .good,
        transactionType: MarketplaceTransactionType = .both
    ) async throws -> MarketplaceListing {
        let insert = MarketplaceListingInsert(
            sellerId: TestUser.id,
            title: title,
            description: description,
            price: price,
            category: category,
            condition: condition,
            transactionType: transactionType,
            imageUrls: ["https://example.com/test-drone.jpg"],
            locationName: "Test Location, CA",
            locationLat: 37.7749,
            locationLng: -122.4194,
            brand: "TestBrand",
            model: "TestModel",
            shippingCost: 10.00
        )

        let listing = try await service.createListing(insert: insert)
        trackForCleanup(table: "marketplace_listings", id: listing.id)
        return listing
    }

    /// Creates an offer by the test user on a listing and tracks it for cleanup.
    @discardableResult
    private func createTestOffer(
        listingId: UUID,
        amount: Decimal = 250.00,
        message: String? = "Integration test offer"
    ) async throws -> UUID {
        try await service.createOffer(
            listingId: listingId,
            buyerId: TestUser.id,
            amount: amount,
            message: message
        )

        // Fetch offers to find the one we just created
        await service.fetchOffersForListing(listingId: listingId)
        guard let offer = service.offers.first(where: {
            $0.amount == amount && $0.message == message
        }) else {
            XCTFail("Created offer not found after fetch")
            return UUID()
        }

        trackForCleanup(table: "marketplace_offers", id: offer.id)
        return offer.id
    }

    /// Creates a ship transaction with test user as seller.
    /// Returns nil and calls XCTSkip if RLS blocks the insert.
    @discardableResult
    private func createTestShipTransaction(
        listingId: UUID,
        amount: Decimal = 300,
        buyerId: UUID = UUID()
    ) async throws -> MarketplaceTransaction {
        let transaction = try await service.createShipTransaction(
            listingId: listingId,
            buyerId: buyerId,
            sellerId: TestUser.id,
            offerId: nil,
            amount: amount
        )
        trackForCleanup(table: "marketplace_transactions", id: transaction.id)
        return transaction
    }

