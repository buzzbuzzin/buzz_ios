    func testCreateAndFetchListing() async throws {
        let listing = try await createTestListing(
            title: "Create Fetch Test Drone",
            description: "Round-trip verification",
            price: 499.99,
            category: .drones,
            condition: .likeNew
        )

        XCTAssertEqual(listing.sellerId, TestUser.id)
        XCTAssertEqual(listing.title, "Create Fetch Test Drone")
        XCTAssertEqual(listing.description, "Round-trip verification")
        XCTAssertEqual(listing.price, 499.99)
        XCTAssertEqual(listing.category, .drones)
        XCTAssertEqual(listing.condition, .likeNew)
        XCTAssertEqual(listing.status, .active)
        XCTAssertEqual(listing.brand, "TestBrand")
        XCTAssertEqual(listing.model, "TestModel")

        // Fetch it back via the service
        let fetched = await service.fetchListingDetail(
            listingId: listing.id,
            currentUserId: TestUser.id
        )
        XCTAssertNotNil(fetched)
        XCTAssertEqual(fetched?.listing.id, listing.id)
        XCTAssertEqual(fetched?.listing.title, "Create Fetch Test Drone")
        XCTAssertEqual(fetched?.listing.price, 499.99)
        XCTAssertFalse(fetched?.sellerFullName.isEmpty ?? true, "Should have seller name from profile join")
    }

