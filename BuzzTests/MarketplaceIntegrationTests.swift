            // PostgREST returns 200 with 0 rows — RLS silently filtered the row
        } catch {
            // RLS explicitly blocked the update — also acceptable
        }
    }

    func testCannotUpdateOtherUsersListing() async throws {
        // Verify that a listing INSERT with a different seller_id is blocked by RLS.
        let otherSellerId = UUID()
        let insert = MarketplaceListingInsert(
            sellerId: otherSellerId,
            title: "Should Be Blocked",
            description: "RLS test",
            price: 100,
            category: .drones,
            condition: .good,
            transactionType: .ship,
            imageUrls: [],
            locationName: nil,
            locationLat: nil,
            locationLng: nil,
            brand: nil,
            model: nil,
            shippingCost: nil
        )

        do {
            let response: [MarketplaceListing] = try await supabase
                .from("marketplace_listings")
                .insert(insert)
                .select()
                .execute()
                .value

            if let created = response.first {
                // If somehow created, clean it up and fail
                trackForCleanup(table: "marketplace_listings", id: created.id)
                XCTFail("RLS should block creating a listing with seller_id != auth user")
            }
            // Empty response means RLS silently blocked it
        } catch {
            // Expected — RLS blocked the insert
        }
    }
