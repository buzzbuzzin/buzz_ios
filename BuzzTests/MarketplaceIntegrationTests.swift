    func testCannotCreateTransactionDirectly() async throws {
        // Attempt raw INSERT into marketplace_transactions where the auth user
        // is neither buyer nor seller — RLS should block it.
        let insert: [String: String] = [
            "listing_id": UUID().uuidString,
            "buyer_id": UUID().uuidString,
            "seller_id": UUID().uuidString,
            "transaction_type": "ship",
            "status": "pending_payment",
            "amount": "100",
            "platform_fee": "10",
            "seller_payout": "90"
        ]

        do {
            try await supabase
                .from("marketplace_transactions")
                .insert(insert)
                .execute()
            XCTFail("RLS should block INSERT when auth user is neither buyer nor seller")
        } catch {
            // Expected — RLS or FK constraint blocked the insert
        }
    }

    func testCannotUpdateTransactionDirectly() async throws {
        // Attempt to UPDATE a transaction where the auth user is not a participant.
        // Using a random UUID means RLS should filter the row out (0 rows affected).
